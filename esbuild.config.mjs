import builtins from "builtin-modules";
import esbuild from "esbuild";
import { readFile } from "node:fs/promises";
import process from "process";

const bundledLicenses = [
	["Better Blockquote Editing", "LICENSE"],
	["@lezer/markdown", "node_modules/@lezer/markdown/LICENSE"],
	["@mnaoumov/obsidian-lib", "node_modules/@mnaoumov/obsidian-lib/LICENSE"],
	["@mnaoumov/typescript-lib", "node_modules/@mnaoumov/typescript-lib/LICENSE"],
	["debug", "node_modules/debug/LICENSE"],
	["ms", "node_modules/ms/license.md"],
	["monkey-around", "licenses/monkey-around.txt"],
];
const notices = await Promise.all(bundledLicenses.map(async ([name, path]) =>
	`/*!\n${name}\n${(await readFile(new URL(path, import.meta.url), "utf8")).trim()}\n*/`));
const banner = ["/* Generated by esbuild. See the plugin repository for source. */", ...notices].join("\n");

const adaptEditorDependencies = {
	name: "adapt-editor-dependencies",
	setup(build) {
		build.onLoad({ filter: /[\\/]@mnaoumov[\\/](obsidian-lib|typescript-lib)[\\/]dist[\\/]lib[\\/]esm[\\/].*\.mjs$/ }, async ({ path }) => {
			const original = await readFile(path, "utf8");
			// The bundled editor and the browser build of debug work without a process shim.
			let contents = original
				.replace(/^function ensureBrowserProcess\(\) \{\r?\n[\s\S]*?^\}\r?\n/m, "")
				.replace(/^ensureBrowserProcess\(\);\r?\n/m, "");
			if (/globalThis\.process|ensureBrowserProcess/.test(contents)) {
				throw new Error(`Unexpected process shim in ${path}`);
			}
			if (/[\\/]embeddable-markdown-editor-component\.mjs$/.test(path)) {
				// Keep the host pane from stealing focus. A background window can
				// retain a focused element, so its editor must never block another pane.
				const guard = /patchHandler: \(\{ fallback \}\) => \{\r?\n\s+if \(isEditorViewFocusedInItsWindow\(scrollableEditor\.activeCM\)\) \{/;
				if (!guard.test(contents)) throw new Error(`Unexpected editor focus guard in ${path}`);
				contents = contents.replace(guard, `patchHandler: ({ fallback, originalArguments: [leaf] }) => {
        if (leaf?.view?.containerEl?.contains(this.containerEl) && isEditorViewFocusedInItsWindow(scrollableEditor.activeCM)) {`);
			}
			if (contents !== original) return { contents, watchFiles: [path] };
		});
	},
};

const prod = (process.argv[2] === "production");

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [adaptEditorDependencies],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
